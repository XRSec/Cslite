import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');

const entryTs = path.join(__dirname, 'src', 'main.ts');
const entryCss = path.join(__dirname, 'src', 'styles.css');
const distDir = path.join(__dirname, 'dist');
const distHtml = path.join(distDir, 'index.html');
const uiBundleTs = path.join(rootDir, 'server', 'src', 'ui-bundle.ts');
const scriptsBundleTs = path.join(rootDir, 'server', 'src', 'scripts-bundle.ts');

const ASSEMBLED_SCRIPTS = [
  [
    [
      'agent/scripts/install/01-cli.sh',
      'agent/scripts/install/02-detect.sh',
      'agent/scripts/install/03-http.sh',
      'agent/scripts/install/04-assets.sh',
      'agent/scripts/install/05-android.sh',
      'agent/scripts/install/06-service.sh',
    ],
    'agent/scripts/install.sh',
    0o755,
  ],
  [
    [
      'agent/scripts/upgrade/01-cli.sh',
      'agent/scripts/install/02-detect.sh',
      'agent/scripts/install/03-http.sh',
      'agent/scripts/upgrade/02-main.sh',
    ],
    'agent/scripts/upgrade.sh',
    0o755,
  ],
  [
    [
      'agent/openwrt/lite/01-env.sh',
      'agent/openwrt/lite/02-json.sh',
      'agent/openwrt/lite/03-http.sh',
      'agent/openwrt/lite/04-config.sh',
      'agent/openwrt/lite/05-metrics.sh',
      'agent/openwrt/lite/06-runtime.sh',
    ],
    'agent/openwrt/cslite-agent-lite.sh',
    0o755,
  ],
];

const SCRIPT_ENTRIES = [
  ['INSTALL_UNIX_SH', 'agent/scripts/install.sh'],
  ['INSTALL_WINDOWS_PS1', 'agent/scripts/install.ps1'],
  ['INSTALL_ANDROID_SH', 'agent/scripts/install-android.sh'],
  ['UPGRADE_UNIX_SH', 'agent/scripts/upgrade.sh'],
  ['UPGRADE_WINDOWS_PS1', 'agent/scripts/upgrade.ps1'],
  ['AGENT_LITE_SH', 'agent/openwrt/cslite-agent-lite.sh'],
  ['AGENT_LITE_PS1', 'agent/scripts/cslite-agent-lite.ps1'],
  ['OPENWRT_INIT_SH', 'agent/openwrt/cslite-agent.init'],
];

function readAgentVersion() {
  const envVer = process.env.CSLITE_AGENT_VERSION?.trim();
  if (envVer) return envVer;
  try {
    const fileVer = fs.readFileSync(path.join(rootDir, 'agent', 'VERSION'), 'utf8').trim();
    if (fileVer) return fileVer;
  } catch { /* ignore */ }
  return 'v1.2.0';
}

function assembleModularScripts(agentVersion) {
  for (const [parts, outRel, mode] of ASSEMBLED_SCRIPTS) {
    let combined = parts.map((p) => fs.readFileSync(path.join(rootDir, p), 'utf8')).join('');
    if (outRel === 'agent/openwrt/cslite-agent-lite.sh') {
      combined = combined.replace(/^VERSION="[^"]*"/m, `VERSION=${JSON.stringify(agentVersion)}`);
    }
    const outPath = path.join(rootDir, outRel);
    fs.writeFileSync(outPath, combined, 'utf8');
    fs.chmodSync(outPath, mode);
  }
}

function buildScriptsBundle() {
  const agentVersion = readAgentVersion();
  assembleModularScripts(agentVersion);
  const lines = [
    '// Auto-generated by web/build.mjs — do not edit manually.',
    ...SCRIPT_ENTRIES.map(([constName, relPath]) => {
      let content = fs.readFileSync(path.join(rootDir, relPath), 'utf8');
      if (constName === 'AGENT_LITE_PS1') {
        content = content.replace(/^\$Version\s*=\s*"[^"]*"/m, `$Version = ${JSON.stringify(agentVersion)}`);
      }
      return `export const ${constName} = ${JSON.stringify(content)};`;
    }),
  ];
  const output = `${lines.join('\n')}\n`;
  fs.mkdirSync(path.dirname(scriptsBundleTs), { recursive: true });
  fs.writeFileSync(scriptsBundleTs, output, 'utf8');
  return Buffer.byteLength(output, 'utf8');
}

export async function buildWeb() {
  const [jsResult, cssResult] = await Promise.all([
    esbuild.build({
      entryPoints: [entryTs],
      bundle: true,
      minify: true,
      format: 'iife',
      target: ['es2022'],
      platform: 'browser',
      write: false,
      legalComments: 'none',
      charset: 'utf8',
    }),
    esbuild.build({
      entryPoints: [entryCss],
      bundle: true,
      minify: true,
      write: false,
      legalComments: 'none',
      charset: 'utf8',
    }),
  ]);

  const rawJs = jsResult.outputFiles[0]?.text ?? '';
  const rawCss = cssResult.outputFiles[0]?.text ?? '';

  const safeJs = rawJs
    .replace(/<\/script/gi, '<\\/script')
    .replace(/<!--/g, '<\\!--');

  const safeCss = rawCss.replace(/<\/style/gi, '<\\/style');

  const html =
    '<!doctype html><html lang="en" data-theme="dark"><head>' +
    '<meta charset="utf-8">' +
    '<meta name="viewport" content="width=device-width,initial-scale=1">' +
    '<title>CSLite — Fleet Control</title>' +
    `<style>${safeCss}</style>` +
    '</head><body>' +
    '<div id="app"></div>' +
    `<script>${safeJs}</script>` +
    '</body></html>';

  fs.mkdirSync(distDir, { recursive: true });
  fs.writeFileSync(distHtml, html, 'utf8');

  fs.mkdirSync(path.dirname(uiBundleTs), { recursive: true });
  fs.writeFileSync(uiBundleTs, `export const UI_HTML = ${JSON.stringify(html)};\n`, 'utf8');

  const scriptsBytes = buildScriptsBundle();

  const bytes = Buffer.byteLength(html, 'utf8');
  return {
    jsBytes: Buffer.byteLength(safeJs, 'utf8'),
    cssBytes: Buffer.byteLength(safeCss, 'utf8'),
    totalBytes: bytes,
    scriptsBytes,
    distHtml,
    uiBundleTs,
    scriptsBundleTs,
  };
}

const isDirectRun =
  process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isDirectRun) {
  const stats = await buildWeb();
  console.log(
    `[web/build] js=${(stats.jsBytes / 1024).toFixed(1)}KB css=${(stats.cssBytes / 1024).toFixed(1)}KB total=${(stats.totalBytes / 1024).toFixed(1)}KB scripts=${(stats.scriptsBytes / 1024).toFixed(1)}KB -> ${path.relative(rootDir, stats.distHtml)}`,
  );
}
